  static String languageNameForCode(String code) {
    return _languageNames[code] ?? code;
  }

  Locale _locale = const Locale('en');
  late SharedPreferences _prefs;

  LocaleProvider() {
    _loadLocale();
  }

  Locale get locale => _locale;

  String get languageName {
    return languageNameForCode(_locale.languageCode);
  }

  Future<void> _loadLocale() async {
    _prefs = await SharedPreferences.getInstance();
    final languageCode = _prefs.getString('locale') ?? 'en';
    _locale = Locale(supportedLanguageCodes.contains(languageCode) ? languageCode : 'en');
    notifyListeners();
  }

  Future<void> setLocale(Locale locale) async {
    if (!supportedLanguageCodes.contains(locale.languageCode)) return;
    _locale = locale;
    await _prefs.setString('locale', locale.languageCode);
    notifyListeners();
  }
